 *
 * ⭐ 生成方式（⛔ 手改本文件）：`python docs/archive/verification/scripts/e46_golden_gen.py`
 *   1. 在 Node vm 里桩掉 DOM/canvas，载入 `docs/archive/e46-tripod-fog-preview.html` 的**原文脚本**
 *      （`boot()` 因此完整跑过：layout → buildCum → setGrabKnots → syncRouteEpoch(true) → genBuildings → bakeAll）；
 *   2. 把 48 栋位图的 `_skirt` 归零（位图归 K5，几何与数学归 K3/K4 ⇒ 两边都读 0）；
 *   3. 探针驱动在**原型作用域内**求值，输出 `logs_temp/e46_golden.json`；
 *   4. 本文件的期望值逐字来自那份 JSON，实际值调 K3/K4/K5 的真实函数。
 *
 * ⚠️ 容差 1e-9（绝对）：两边都是 IEEE double 且运算顺序一致，但 `sin/cos/exp/pow` 在
 *    V8 与 HotSpot 上不保证逐位相同（实现不同的 fdlibm）⇒ ⛔ 用 0.0 容差。
 * ⚠️ `scene.*` / `fp*` 读的是 world 上的**预分配缓冲**（R12）⇒ 每条探针各自算、立刻比，
 *    ⛔ 先攒一批 scene 再比（读到的是最后一帧）。
 * ⚠️ `bld` 的 `skirtFrac/skirtA` 恒 0：setup 烘完当场归零（JS 侧同样把 `_skirt` 归零）；而**几何走生产 `TripodFogBake.genBuildings`**——两带共用一支 LCG 的保真度靠本文件守。
 * ⚠️ K5 的 `fogA/fogB`（雾条逐像素 + T6 四条判据）、`grade`（暗角+颗粒逐像素）是**逐位**
 *    对账（含 `Uint8ClampedArray` 的 ties-to-even 量化）；`bld.acc` 只对账**记账值**
 *    （雾裙/羽化的实际落笔值 + carves 矩形）—— 多边形 AA 与 canvas 栅格化器有意不同。
 */
