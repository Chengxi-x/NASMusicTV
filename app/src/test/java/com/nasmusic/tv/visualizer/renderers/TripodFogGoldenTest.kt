     *    绿灯，最后是 T14 的负样本才把它咬出来（D19 的近景带位置前提）。
     *
     * ⚠️ `bakeBuilding` 会把 `skirtFrac/skirtA/featherW/featherTop` **回填进建筑**，而 `scene.*` 探针要求
     *    它们恒 0（位图归 K5 的口径，JS 侧同样把 48 栋的 `_skirt` 归零）⇒ 烘完当场归零。
