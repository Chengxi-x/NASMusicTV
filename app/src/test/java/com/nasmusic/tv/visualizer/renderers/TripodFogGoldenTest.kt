    /** 一条雾条的 `[seam, seamBad, step, stepBad]` + 采样点的 RGBA（打包 ARGB 拆回）。 */
    private fun fogStripArr(w: Int, h: Int, cells: Int, seed: Int, smp: IntArray): DoubleArray {
        val b = TripodFogBake.bakeFogStrip(w, h, cells, seed, 5, 1.0)
        val o = ArrayList<Double>(4 + smp.size * 2)
        o.add(b.seam); o.add(b.seamBad); o.add(b.step); o.add(b.stepBad)
        var s = 0
        while (s < smp.size) {
            val p = b.px[smp[s + 1] * b.w + smp[s]]
            o.add(((p ushr 16) and 0xFF).toDouble())
            o.add(((p ushr 8) and 0xFF).toDouble())
            o.add((p and 0xFF).toDouble())
            o.add(((p ushr 24) and 0xFF).toDouble())
            s += 2
        }
        return o.toDoubleArray()
    }

    /** grade 位图 8 个采样点的 (R, A)（原型 bakeGrade 读全局 W=960/H=540/cx=480；⛔ 棱线 D31）。 */
    private fun gradeArr(): DoubleArray {
        val px = TripodFogBake.bakeGrade(960, 540, 480.0, world.params.grain)
        val o = ArrayList<Double>(16)
        var s = 0
        while (s < GRAD_SAMPLE.size) {
            val p = px[GRAD_SAMPLE[s + 1] * 960 + GRAD_SAMPLE[s]]
            o.add(((p ushr 16) and 0xFF).toDouble())
            o.add(((p ushr 24) and 0xFF).toDouble())
            s += 2
        }
        return o.toDoubleArray()
    }

    /**
     * 48 栋的烘焙记账（⛔ 不含像素：多边形 AA 与 canvas 栅格化器**有意**不同，见 K5 文件头）：
     * 每栋 `[skirtFrac, skirtA, featherW, featherTop, inks.size, carves.size, carves×4]`。
     */
    private fun bldAccArr(): DoubleArray {
        val o = ArrayList<Double>()
        for (b in world.bMid) bldAcc1(o, b)
        for (b in world.bNear) bldAcc1(o, b)
        return o.toDoubleArray()
    }

    private fun bldAcc1(o: ArrayList<Double>, src: TripodBuilding) {
        val b = TripodBuilding()
        b.i = src.i; b.pool = src.pool; b.x = src.x; b.z0 = src.z0
        b.w = src.w; b.h = src.h; b.dep = src.dep
        b.seed = src.seed; b.k = src.k
        val cv = TripodFogBake.bakeBuilding(b, world.params)
        o.add(cv.skirtFrac); o.add(cv.skirtA); o.add(cv.featherW); o.add(cv.featherTop)
        o.add(cv.inks.size.toDouble()); o.add(cv.carves.size.toDouble())
        for (c in cv.carves) { o.add(c.x); o.add(c.y); o.add(c.w); o.add(c.h) }
    }

