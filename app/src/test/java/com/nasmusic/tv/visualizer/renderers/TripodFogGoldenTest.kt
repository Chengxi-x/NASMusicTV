    /**
     * 原型的**整条楼场生成**：走生产入口 `TripodFogBake.genBuildings`（连 `bakeBuilding` 一起），
     * ⛔ 不许在这里另写一份几何抽样（那会再立一个事实源，E44 D24）。
     *
     * ⭐ 用生产函数而不是复刻抽样，81 条探针才会**真的吃到** `mk()` 的 r() 顺序：两条带必须共用同一支
