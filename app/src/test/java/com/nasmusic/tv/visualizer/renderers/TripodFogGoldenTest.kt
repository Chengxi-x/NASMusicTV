        TripodFogBake.genBuildings(world, world.params)
        for (b in world.bMid + world.bNear) {
            b.skirtFrac = 0.0
            b.skirtA = 0.0
            b.featherW = 0.0
            b.featherTop = 0.0
        }
    }

