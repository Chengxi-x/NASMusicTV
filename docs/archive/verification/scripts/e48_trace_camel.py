def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ref', default=os.path.join(REPO, 'logs_temp', 'e48_ref_camel.png'))
    ap.add_argument('--h', type=int, default=128, help='缩小后的 ink 高（归一格）')
    ap.add_argument('--eps', type=float, default=1.0)
    ap.add_argument('--scratch', default=os.path.join(REPO, 'logs_temp'))
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--html', default=HTML)
    a = ap.parse_args()

    if not os.path.exists(a.ref):
        sys.exit('参考图不存在：' + a.ref + '（所有者给的图只在 gitignored 的 logs_temp/ ⇒ 未决项 2）')
    refc = load_refc()
    os.makedirs(a.scratch, exist_ok=True)
    m0, im0 = mask_of(a.ref)
    c0 = crop(m0)
    print('墨口径：与 `e48_ref_camel.py` 同一条（alpha>128 且 RGB 均值<160）——本脚本不另立判据')
    print('参考图 %s (%d×%d)  ink bbox %d×%d  长/高=%.3f'
          % (os.path.relpath(a.ref, REPO).replace('\\', '/'), im0.size[0], im0.size[1],
             c0.shape[1], c0.shape[0], c0.shape[1] / c0.shape[0]))
    print('\n── ① 原图（权威口径直接跑）──')
    r0 = measure(refc, a.ref)
    print(r0['text'], end='')

    dm = downscale(c0, a.h)
    ih, iw = dm.shape
    dpath = os.path.join(a.scratch, 'e48_tex_down.png')
    save_png(dm, dpath)
    print('── ② 缩到 ink 高 %d px（面积平均 + 0.5 二值化）⇒ **量化台阶在这一步产生** ──' % a.h)
    print('  归一格 %d×%d  长/高=%.3f（原图 %.3f，差 %+.1f%%）'
          % (iw, ih, iw / ih, c0.shape[1] / c0.shape[0],
             100.0 * ((iw / ih) / (c0.shape[1] / c0.shape[0]) - 1)))
    rd = measure(refc, dpath)
    print(rd['text'], end='')

    raw = contours(dm)
    rings = sorted([simplify(r, a.eps) for r in raw], key=lambda r: -len(r))
    print('\n── ③ 描边 + Douglas-Peucker（eps=%.2f 归一格 px）──' % a.eps)
    print('  环 %d 条（外轮廓 + 孔洞同表，`evenodd`）；顶点 %d → %d；最大环 %d 顶点'
          % (len(rings), sum(len(r) for r in raw), sum(len(r) for r in rings), len(rings[0])))

    pm = fill_evenodd(rings, iw, ih)
    ppath = os.path.join(a.scratch, 'e48_tex_poly.png')
    save_png(pm, ppath)
    inter, union = int((pm & dm).sum()), int((pm | dm).sum())
    tol = dm | np.pad(dm, 1, mode='edge')[1:-1, 1:-1]
    print('\n── ④ 化简回测（自实现 even-odd 栅格 vs 缩小位图）──')
    print('  IoU=%.4f  面积 %+d px（%+.2f%%）  ⭐ ±1 px 容忍后=%.4f ⇒ 丢的只是**半像素边缘台阶**，'
          '⛔ 不是形状' % (inter / union, int(pm.sum()) - int(dm.sum()),
                          100.0 * (pm.sum() / dm.sum() - 1),
                          int((pm & tol).sum() + (~pm & ~dm & tol).sum()) / (iw * ih)))
    rp = measure(refc, ppath)
    print(rp['text'], end='')
    print('  ── ⑤ 描边造成的轴漂移（④ 相对 ②）──')
    print('  外接框 %s×%s → %s×%s   长/高 %.3f → %.3f'
          % (rd['len'][0], rd['len'][1], rp['len'][0], rp['len'][1],
             int(rd['len'][0]) / int(rd['len'][1]), int(rp['len'][0]) / int(rp['len'][1])))
    print('  峰/体深 %s → %s   腿/全高 %s → %s   峰宽/峰高 左 %s→%s 右 %s→%s'
          % (rd['depth'][2], rp['depth'][2], rd['leg'][1], rp['leg'][1],
             rd['w'][2], rp['w'][2], rd['w'][5], rp['w'][5]))
    print('  肩凹行 %s → %s   腹线行 %s → %s   蹄行 %s → %s   颈背列 %s → %s'
          % (rd['humps'][4], rp['humps'][4], rd['humps'][5], rp['humps'][5],
             rd['humps'][6], rp['humps'][6], rd['neck'][0], rp['neck'][0]))

    print('\n── ⑥ 锚点与挂点（**一律取④=真正要画出来的那一坨**，⛔ 取②：`--eps` 一变锚点必须跟着变）──')
    rearR, rearX, frontR, frontX, sadR, belly, hoof = [int(v) for v in rp['humps']]
    neckX = int(rp['neck'][0])
    tx0, tx1 = int(rp['torso'][0]), int(rp['torso'][1])
    top = np.full(iw, 10 ** 9)
    for x in range(iw):
        col = np.nonzero(pm[:, x])[0]
        if col.size:
            top[x] = col[0]
    a_, b_ = sorted([rearX, frontX])
    sadXi = a_ + int(np.argmax(top[a_:b_ + 1]))
    assert int(top[sadXi]) == sadR, '肩凹列推导 %d 的行 %d ≠ 权威行 %d ⇒ 口径漂了' % (sadXi, top[sadXi], sadR)
    yleg, legs, legw = leg_runs(pm, belly)
    F = dict(eps=a.eps, sad=float(sadXi), neck=float(neckX), tx0=float(tx0), tx1=float(tx1),
             rearx=float(rearX), frontx=float(frontX), belly=belly, legs=legs,
             legw=[float(v) for v in legw], rings=rings)
