def load_refc():
    """按路径 import `e48_ref_camel.py` ⇒ 解剖量的**唯一**口径。"""
    spec = importlib.util.spec_from_file_location('e48_ref_camel', os.path.join(HERE, 'e48_ref_camel.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def measure(refc, path):
    """跑 `refc.main(path)` 并把它打印的行数**正则回读**回来（⛔ 自己再算一遍）。"""
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        refc.main(path)
    txt = buf.getvalue()
    pats = {
        'len': r'lenPx=(\d+) highPx=(\d+)',
        'humps': r'左峰顶=行(\d+)\(x=(-?\d+)\)\s+右峰顶=行(\d+)\(x=(-?\d+)\)\s+肩凹=行(\d+)\s+腹线=行(\d+)\s+蹄=行(\d+)',
        'belly': r'腹线=行(\d+)\s+蹄=行(\d+)',
        'depth': r'humpRisePx=(-?\d+)\s+bodyDepthPx=(-?\d+)\s+\*\*峰/体深=([\d.]+)\*\*',
        'leg': r'legPx=(\d+)\s+腿/全高=([\d.]+)',
        'w': r'左峰 rise=(\d+).*?峰宽=(\d+)\s+\*\*宽/高=([\d.]+)\*\*.*?右峰 rise=(\d+).*?峰宽=(\d+)\s+\*\*宽/高=([\d.]+)\*\*',
        'neck': r'颈背相接=外接框内列(\d+)\s+头顶=行(\d+)\s+右峰顶=行(\d+)',
        'torso': r'躯干跨（腹线行）x=(\d+)–(\d+)\s*=\s*(\d+) px',
    }
    d = {}
    for k, p in pats.items():
        m = re.search(p, txt, re.S)
        assert m, '回读失败：' + k + '（`e48_ref_camel.py` 的输出格式变了 ⇒ 这里必须同步，⛔ 放行）'
        d[k] = m.groups()
    d['text'] = txt
    return d


def mask_of(path):
    """与 `e48_ref_camel.INK` **同一条**判据的 numpy 掩膜。"""
    im = Image.open(path).convert('RGBA')
    a = np.asarray(im).astype(np.int32)
    m = (a[:, :, 3] > 128) & (a[:, :, :3].mean(axis=2) < 160.0)
    return m, im


def crop(m):
    ys, xs = np.nonzero(m)
    return m[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def downscale(m, target_h):
    """面积平均（= 浏览器 `drawImage` 缩小时做的事），再按 0.5 重新二值化。
    ⛔ 最近邻：那会把所有者贴图的锯齿原样搬进点表，量化台阶不可控。"""
    ih, iw = m.shape
    tw = max(2, int(round(iw * target_h / ih)))
    src = m.astype(np.float64)
    out = np.zeros((target_h, tw), np.float64)
    for y in range(target_h):
        y0, y1 = y * ih / target_h, (y + 1) * ih / target_h
        for x in range(tw):
            x0, x1 = x * iw / tw, (x + 1) * iw / tw
            acc = 0.0
            for yy in range(int(np.floor(y0)), min(int(np.ceil(y1)), ih)):
                vy = min(yy + 1, y1) - max(yy, y0)
                for xx in range(int(np.floor(x0)), min(int(np.ceil(x1)), iw)):
                    vx = min(xx + 1, x1) - max(xx, x0)
                    acc += src[yy, xx] * vy * vx
            out[y, x] = acc / ((y1 - y0) * (x1 - x0))
    return out >= 0.5


def ascii_view(m, cols=64):
    ih, iw = m.shape
    rows = max(8, int(cols * ih / iw * 0.5))
    lines = []
    for r in range(rows):
        line = ''
        for c in range(cols):
            x0 = int(c * iw / cols)
            x1 = max(x0 + 1, int((c + 1) * iw / cols))
            y0 = int(r * ih / rows)
            y1 = max(y0 + 1, int((r + 1) * ih / rows))
            f = m[y0:y1, x0:x1].mean()
            line += ' ' if f == 0 else ('.' if f < 0.35 else ('o' if f < 0.8 else '#'))
        lines.append(line)
    return '\n'.join(lines)


def contours(m):
    """曼哈顿边界边提取 + 链接成闭合环（外轮廓与孔洞一视同仁，`evenodd` 填充不需要方向）。
    顶点是**像素角点**：列 x ∈ [0, iw]，行 y ∈ [0, ih]。"""
    ih, iw = m.shape
    p = np.zeros((ih + 2, iw + 2), bool)
    p[1:-1, 1:-1] = m
    out = defaultdict(list)

    def add(ax, ay, bx, by):
        out[(ax, ay)].append((bx, by))

    ys, xs = np.nonzero(m)
    for x, y in zip(xs, ys):
        X, Y = x + 1, y + 1                      # padded 坐标
        if not p[Y - 1, X]:
            add(X, Y, X + 1, Y)
        if not p[Y + 1, X]:
            add(X + 1, Y + 1, X, Y + 1)
        if not p[Y, X - 1]:
            add(X, Y + 1, X, Y)
        if not p[Y, X + 1]:
            add(X + 1, Y, X + 1, Y + 1)
    total = sum(len(v) for v in out.values())
    rings, used = [], set()
    for s in sorted(out):
        for e in out[s]:
            if (s, e) in used:
                continue
            ring, cur, nxt = [s], s, e
            while True:
                used.add((cur, nxt))
                ring.append(nxt)
                cur = nxt
                cands = [v for v in out[cur] if (cur, v) not in used]
                if not cands:
                    break
                nxt = cands[0]
                if nxt == ring[0]:
                    used.add((cur, nxt))
                    break
            if len(ring) > 3:
                rings.append(ring)
    n = sum(len(r) for r in rings)
    assert abs(n - total) <= 4 * len(rings), \
        '环顶点数 %d vs 边数 %d ⇒ 链接漏环（对角接触处每环最多多 4 个顶点）' % (n, total)
    return rings


def dp(pts, eps):
    """Douglas–Peucker（开链），返回保留点的下标。"""
    if len(pts) < 3:
        return [0, len(pts) - 1]
    a, b = np.asarray(pts[0], float), np.asarray(pts[-1], float)
    d = b - a
    L2 = float(d @ d)
    dist, keep = -1.0, 0
    for i in range(1, len(pts) - 1):
        q = np.asarray(pts[i], float) - a
        t = 0.0 if L2 == 0 else max(0.0, min(1.0, float(q @ d) / L2))
        v = q - t * d
        dd = float(v @ v)
        if dd > dist:
            dist, keep = dd, i
    if dist > eps * eps:
        left = dp(pts[:keep + 1], eps)
        right = [keep + i for i in dp(pts[keep:], eps)[1:]]
        return left + right
    return [0, len(pts) - 1]


def simplify(ring, eps):
    """闭环：按「离首点最远」劈成两条开链各自化简（劈点必留 ⇒ 环不会缩成一条线）。"""
    if len(ring) <= 4:
        return list(ring)
    p0 = np.asarray(ring[0], float)
    far = max(range(1, len(ring)), key=lambda i: float(np.sum((np.asarray(ring[i], float) - p0) ** 2)))
    a, b = ring[:far + 1], ring[far:] + [ring[0]]
    ka, kb = dp(a, eps), dp(b, eps)
    return [a[i] for i in ka] + [b[i] for i in kb[1:-1]]


def fill_evenodd(rings, iw, ih):
    """自实现 even-odd 栅格化（`PIL.ImageDraw.polygon` 是 non-zero，孔洞会被填实 ⇒ 回测失真）。
    扫描线取 `y+0.5`，边按半开区间 `lo <= y+0.5 < hi` 取交叉 ⇒ 顶点不重复计数。"""
    g = np.zeros((ih, iw), bool)
    segs = []
    for r in rings:
        for i in range(len(r) - 1):
            (ax, ay), (bx, by) = r[i], r[i + 1]
            if ay != by:
                segs.append((ay, by, ax, bx))
    for y in range(ih):
        yy = y + 0.5
        xs = []
        for ay, by, ax, bx in segs:
            lo, hi = (ay, by) if ay < by else (by, ay)
            if lo <= yy < hi:
                xs.append(ax + (bx - ax) * ((yy - ay) / (by - ay)))
        xs.sort()
        for i in range(0, len(xs) - 1, 2):
            xa = int(np.ceil(xs[i] - 0.5))
            xb = int(np.floor(xs[i + 1] - 0.5))
            for x in range(max(0, xa), min(iw, xb + 1)):
                g[y, x] = True
    return g


def save_png(mask, path):
    a = np.zeros((mask.shape[0], mask.shape[1], 4), np.uint8)
    a[mask] = (20, 20, 20, 255)                 # 均值 20 ⇒ 稳过 `e48_ref_camel` 的墨判据（<160）
    Image.fromarray(a, 'RGBA').save(path)


def leg_runs(mask, belly):
    """腹线↔蹄中间那一行的各段游程 ⇒ (中心, 宽)（TEXLEGS 的腿挂点与腿宽，⛔ 沿用 PROC 的腿距/腿宽）。"""
    ih, iw = mask.shape
    y = (belly + ih - 1) // 2
    runs, cur = [], 0
    for x in range(iw):
        if mask[y, x]:
            cur += 1
        elif cur:
            if cur >= 2:
                runs.append(cur)
            cur = 0
    if cur >= 2:
        runs.append(cur)
    cs, i = [], 0
    for r in runs:
        while i < iw and not mask[y, i]:
            i += 1
        cs.append(i + r / 2.0)
        i += r
    return y, cs, runs


